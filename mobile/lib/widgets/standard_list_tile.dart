import 'package:flutter/material.dart';

class const StandardListTile({
  super.key,
  required final Widget title,
  final Widget? subtitle,
  final Widget? leading,
  final Widget? trailing,
  final VoidCallback? onTap,
  final bool enabled = true,
  final bool selected = false,
  final TextStyle? titleTextStyle,
  final TextStyle? subtitleTextStyle,
  final EdgeInsetsGeometry? contentPadding,
  final bool? dense,
  final VisualDensity? visualDensity,
  final Color? tileColor,
  final Color? selectedTileColor,
  final bool? enableFeedback,
  final double? horizontalTitleGap,
  final double? minVerticalPadding,
  final double? minLeadingWidth,
  final bool isThreeLine = false,
  final ShapeBorder? shape,
  final FocusNode? focusNode,
  final bool autofocus = false,
  final MouseCursor? mouseCursor,
  final VoidCallback? onLongPress,
  final TextStyle? leadingAndTrailingTextStyle,
  final ListTileTitleAlignment? titleAlignment,
  final EdgeInsetsGeometry? cardMargin,
  final double? cardElevation,
  final ShapeBorder? cardShape,
  final Color? cardColor,
  final Color? cardShadowColor,
  final Color? cardSurfaceTintColor,
  final bool cardBorderOnForeground = true,
  final bool cardSemanticContainer = true,
  final Clip? cardClipBehavior,
}) extends StatelessWidget {
  // Card properties
  @override
  Widget build(BuildContext context) {
    return Card(
      margin: cardMargin,
      elevation: cardElevation,
      shape: cardShape,
      color: cardColor,
      shadowColor: cardShadowColor,
      surfaceTintColor: cardSurfaceTintColor,
      borderOnForeground: cardBorderOnForeground,
      semanticContainer: cardSemanticContainer,
      clipBehavior: cardClipBehavior,
      child: ListTile(
        title: title,
        subtitle: subtitle,
        leading: leading,
        trailing: trailing,
        onTap: onTap,
        enabled: enabled,
        selected: selected,
        titleTextStyle: titleTextStyle,
        subtitleTextStyle: subtitleTextStyle,
        contentPadding: contentPadding,
        dense: dense,
        visualDensity: visualDensity,
        tileColor: tileColor,
        selectedTileColor: selectedTileColor,
        enableFeedback: enableFeedback,
        horizontalTitleGap: horizontalTitleGap,
        minVerticalPadding: minVerticalPadding,
        minLeadingWidth: minLeadingWidth,
        isThreeLine: isThreeLine,
        shape: shape,
        focusNode: focusNode,
        autofocus: autofocus,
        mouseCursor: mouseCursor,
        onLongPress: onLongPress,
        leadingAndTrailingTextStyle: leadingAndTrailingTextStyle,
        titleAlignment: titleAlignment,
      ),
    );
  }
}
